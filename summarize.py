def summarize(data: dict, storylines: dict) -> str:
    """
    Sends the fetched game date + all game results + detected storylines to
    Claude, and returns a Hebrew, sportscaster-style prose summary covering
    every game (plain text, no markdown headers).
    """
    from storylines import all_game_results

    client = anthropic.Anthropic()

    user_content = json.dumps(
        {
            "date": data["date"],
            "is_playoffs": data.get("is_playoffs", False),
            "is_cup_knockout": data.get("is_cup_knockout", False),
            "is_play_in": data.get("is_play_in", False),
            "all_games": all_game_results(data["games"]),
            "storylines": storylines,
        },
        ensure_ascii=False,
        default=str,
    )

    response = client.messages.create(
        model=MODEL,
        max_tokens=2000,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": user_content}],
    )

    return next(block.text for block in response.content if block.type == "text")


